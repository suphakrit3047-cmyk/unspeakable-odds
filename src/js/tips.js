function tip(id) {
  if (!run || run.mode !== 'run' || seenTips.includes(id)) return;
  if (run.tip && run.tip !== id) {
    seenTips.push(run.tip);
    store(TIPKEY, seenTips);
  }
  run.tip = id;
}
function tipHTML() {
  return run && run.tip
    ? `<span class="eyebrow">ของใหม่</span><p>${TIPS[run.tip]}</p><button class="btn tipok" data-tipok>เข้าใจแล้ว</button>`
    : '';
}
function paintTip(sel) {
  const b = $(sel);
  const h = tipHTML();
  b.innerHTML = h;
  b.hidden = !h;
}
document.addEventListener('click', ev => {
  if (!ev.target.closest('[data-tipok]')) return;
  seenTips.push(run.tip);
  store(TIPKEY, seenTips);
  run.tip = null;
  ['#coach', '#c-coach', '#r-coach', '#i-coach', '#ev-coach', '#rs-coach'].forEach(sel => {
    const b = $(sel);
    if (b && !b.closest('section').hidden) {
      if (sel === '#coach') renderCoach();
      else paintTip(sel);
    }
  });
});
